// Joins the migrations and the seed into one file to paste into the Supabase SQL editor.
// The demo passcodes (dev_seed.sql) are deliberately left out.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..', 'supabase');
const files = [...readdirSync(join(root, 'migrations')).sort().map((f) => join('migrations', f)), 'seed.sql'];

export function buildSetupSql() {
  const parts = files.map((f) => `-- ===== ${f.replace(/\\/g, '/')} =====\n${readFileSync(join(root, f), 'utf8').trim()}\n`);
  return [
    '-- Bachelor party site: one-off database set-up. Generated by scripts/build-setup-sql.mjs: do not edit.',
    '-- Paste the whole file into the Supabase SQL editor and run it once, on an empty project.',
    '-- It runs as one transaction: if anything fails, nothing is changed.',
    '',
    'begin;',
    '',
    ...parts,
    'commit;',
    '',
  ].join('\n');
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(join(root, 'setup.sql'), buildSetupSql());
  console.log('Wrote supabase/setup.sql');
}
