-- Site switches, e.g. whether the groom view is published.
create table app_settings (
  key        text primary key,
  value      text not null,
  updated_at timestamptz not null default now()
);

-- Audit trail (section 6): who, when and the old value.
create table audit_log (
  id         bigint generated by default as identity primary key,
  table_name text not null,
  row_id     text not null,
  action     text not null check (action in ('insert', 'update', 'delete')),
  actor      text not null,
  at         timestamptz not null default now(),
  old_row    jsonb,
  new_row    jsonb
);

-- The app sets `app.actor` for the transaction; otherwise the actor is "system".
create function audit_row() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  who text := coalesce(nullif(current_setting('app.actor', true), ''), 'system');
begin
  if tg_op = 'INSERT' then
    insert into audit_log (table_name, row_id, action, actor, new_row)
    values (tg_table_name, to_jsonb(new) ->> coalesce(tg_argv[0], 'id'), 'insert', who, to_jsonb(new));
    return new;
  elsif tg_op = 'UPDATE' then
    if to_jsonb(old) is distinct from to_jsonb(new) then
      insert into audit_log (table_name, row_id, action, actor, old_row, new_row)
      values (tg_table_name, to_jsonb(old) ->> coalesce(tg_argv[0], 'id'), 'update', who, to_jsonb(old), to_jsonb(new));
    end if;
    return new;
  else
    insert into audit_log (table_name, row_id, action, actor, old_row)
    values (tg_table_name, to_jsonb(old) ->> coalesce(tg_argv[0], 'id'), 'delete', who, to_jsonb(old));
    return old;
  end if;
end $$;

create trigger audit_options        after insert or update or delete on options        for each row execute function audit_row();
create trigger audit_assumptions    after insert or update or delete on assumptions    for each row execute function audit_row();
create trigger audit_fx_rates       after insert or update or delete on fx_rates       for each row execute function audit_row();
create trigger audit_scenarios      after insert or update or delete on scenarios      for each row execute function audit_row();
create trigger audit_decisions      after insert or update or delete on decisions      for each row execute function audit_row();
create trigger audit_open_questions after insert or update or delete on open_questions for each row execute function audit_row();
create trigger audit_app_settings   after insert or update or delete on app_settings   for each row execute function audit_row('key');

-- Decisions and the audit trail cannot be deleted; the audit trail cannot be edited.
create function forbid_change() returns trigger
language plpgsql as $$
begin
  raise exception '% rows cannot be %', tg_table_name, case tg_op when 'DELETE' then 'deleted' else 'changed' end;
end $$;

create trigger decisions_no_delete before delete on decisions for each row execute function forbid_change();
create trigger audit_log_immutable before update or delete on audit_log for each row execute function forbid_change();

