-- Bachelor party site: schema (stage a)
-- Spec: docs/requirements.md section 4.
-- Money: integer USD cents, plus the currency the figure was quoted in.
-- GBP is never stored as a total; it is derived from fx_rates at display time.

-- ---------------------------------------------------------------------------
-- Core tables (section 4)
-- ---------------------------------------------------------------------------

create table cities (
  id   text primary key,
  name text not null unique
);

-- Pages the research took figures from.
create table sources (
  id           bigint generated by default as identity primary key,
  slug         text not null unique,
  title        text not null,
  url          text,                      -- null for a person (e.g. the organiser)
  date_checked date not null,
  publisher    text,
  notes        text
);

-- One row per hotel, activity, transfer, flight or payment tool.
create table options (
  id                   bigint generated by default as identity primary key,
  slug                 text not null unique,
  city_id              text references cities (id),   -- null: not city-specific, or city TBC
  category             text not null check (category in ('stay', 'activity', 'food', 'transport', 'payment')),
  name                 text not null,
  tier                 text check (tier in ('budget', 'mid', 'premium')),
  price_amount         integer check (price_amount >= 0),       -- USD cents; null: price not known
  price_amount_high    integer check (price_amount_high >= 0),  -- USD cents; top of a quoted range
  price_unit           text not null check (price_unit in ('per_person', 'per_room_night', 'flat')),
  currency             text not null default 'USD' check (currency in ('USD', 'GBP')),  -- currency quoted in
  quoted_amount        integer check (quoted_amount >= 0),      -- minor units of `currency`, when not USD
  quoted_amount_high   integer check (quoted_amount_high >= 0),
  price_note           text,
  lead_time_days       integer check (lead_time_days >= 0),
  lead_time_note       text,
  status               text not null default 'shortlist' check (status in ('shortlist', 'chosen', 'rejected')),
  groom_fit_note       text,
  notes                text,
  verified             boolean not null default false,          -- unverified is the default
  model_input          boolean not null default false,          -- the row the cost calculator reads
  excluded_from_totals boolean not null default false,          -- flights: shown, never summed
  created_at           timestamptz not null default now(),
  check (price_amount_high is null or price_amount is not null),
  check (currency = 'USD' or price_amount is null or quoted_amount is not null),
  check (not model_input or (price_amount is not null and tier is not null and city_id is not null)),
  check (not (model_input and excluded_from_totals))
);

-- The calculator needs exactly one stay rate and one transfer fare per city and tier.
create unique index options_one_model_input on options (city_id, category, tier) where model_input;

-- Saved calculator runs.
create table scenarios (
  id            bigint generated by default as identity primary key,
  name          text not null,
  city_id       text not null references cities (id),
  tier          text not null check (tier in ('budget', 'mid', 'premium')),
  nights        integer not null check (nights in (2, 3)),
  group_size    integer not null check (group_size > 0),
  local_guests  integer not null default 0 check (local_guests >= 0),
  groom_covered boolean not null default true,
  created_at    timestamptz not null default now(),
  check (local_guests < group_size)
);

-- Assumptions register (FR-11). `value` holds numbers; `value_text` holds facts
-- that are not numbers (dates, headcount range). Money values are USD cents.
create table assumptions (
  id          bigint generated by default as identity primary key,
  key         text not null,
  city_id     text references cities (id),   -- null: applies to both cities
  value       numeric,
  value_text  text,
  unit        text not null check (unit in ('percent', 'usd_cents', 'beds', 'legs', 'flag', 'text')),
  currency    text check (currency in ('USD', 'GBP')),  -- currency quoted in, for money values
  reason      text,
  status_note text,                           -- e.g. "Confirmed by Jack", "Sources conflict"
  verified    boolean not null default false,
  created_at  timestamptz not null default now(),
  check (value is not null or value_text is not null),
  check (unit <> 'usd_cents' or (value = trunc(value) and currency is not null)),
  unique nulls not distinct (key, city_id)
);

-- Latest row wins; history is kept.
create table fx_rates (
  id         bigint generated by default as identity primary key,
  from_ccy   text not null check (from_ccy in ('USD', 'GBP')),
  to_ccy     text not null check (to_ccy in ('USD', 'GBP')),
  rate       numeric(12, 6) not null check (rate > 0),
  as_of      date not null,
  source_id  bigint references sources (id),
  note       text,
  created_at timestamptz not null default now(),
  check (from_ccy <> to_ccy)
);

-- Links any option, assumption or FX rate to the source it came from.
create table source_links (
  id              bigint generated by default as identity primary key,
  source_id       bigint not null references sources (id),
  entity_type     text not null check (entity_type in ('option', 'assumption', 'fx_rate', 'decision', 'open_question')),
  entity_id       bigint not null,
  quote_or_figure text,
  unique (source_id, entity_type, entity_id)
);

-- Where sources disagree, or the only source is weak. Both values are kept.
create table conflicts (
  id          bigint generated by default as identity primary key,
  entity_type text not null check (entity_type in ('option', 'assumption', 'fx_rate')),
  entity_id   bigint not null,
  title       text not null,
  source_a    bigint references sources (id),   -- null: page not recorded in research
  source_b    bigint references sources (id),
  value_a     text not null,
  value_b     text,
  used        text not null,
  why         text not null
);

-- Append-only: rows cannot be deleted, only superseded. Edits are audited.
create table decisions (
  id                bigint generated by default as identity primary key,
  date              date not null,
  title             text not null,
  decision          text not null,
  reason            text,
  decided_by        text not null,
  linked_option_ids bigint[] not null default '{}',
  superseded_by     bigint references decisions (id),
  created_at        timestamptz not null default now()
);

create table open_questions (
  id                    bigint generated by default as identity primary key,
  question              text not null,
  owner                 text not null,
  status                text not null default 'open' check (status in ('open', 'answered')),
  answer                text,
  closed_by_decision_id bigint references decisions (id),
  created_at            timestamptz not null default now(),
  -- Closing a question requires the decision that answers it.
  constraint answered_needs_decision check (status = 'open' or closed_by_decision_id is not null)
);

-- ---------------------------------------------------------------------------
-- Supporting tables (section 4)
-- Privacy: name and currency only. No contact, card or bank details anywhere.
-- ---------------------------------------------------------------------------

create table guests (
  id           bigint generated by default as identity primary key,
  name         text not null,
  home_country text,
  bed_needed   boolean not null default true,
  role         text not null default 'group' check (role in ('organiser', 'group', 'groom')),
  currency     text not null check (currency in ('USD', 'GBP'))
);

-- Records only. No payment processing.
create table payments (
  id            bigint generated by default as identity primary key,
  guest_id      bigint not null references guests (id),
  amount        integer not null check (amount >= 0),   -- USD cents
  currency      text not null check (currency in ('USD', 'GBP')),  -- currency the guest is quoted in
  quoted_amount integer check (quoted_amount >= 0),     -- minor units of `currency`, when not USD
  due_date      date,
  paid_date     date
);

create table votes (
  id        bigint generated by default as identity primary key,
  option_id bigint not null references options (id),
  guest_id  bigint not null references guests (id),
  vote      smallint not null check (vote in (-1, 1)),
  unique (option_id, guest_id)
);

create table comments (
  id          bigint generated by default as identity primary key,
  entity_type text not null check (entity_type in ('option', 'decision', 'open_question')),
  entity_id   bigint not null,
  guest_id    bigint not null references guests (id),
  body        text not null,
  created_at  timestamptz not null default now()
);

